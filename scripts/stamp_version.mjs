import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const run = (process.env.GITHUB_RUN_NUMBER || "").trim();
const shaFull = (process.env.GITHUB_SHA || "").trim();
const build = /^\d+$/.test(run) ? run : "dev";
const sha = /^[0-9a-f]{7,}$/i.test(shaFull) ? shaFull.slice(0, 7) : "dev";
const installer = /^\d+$/.test(run) ? `0.1.${run}` : "0.1.0";

const info = `// Generated by scripts/stamp_version.mjs. Local fallback is dev.
export const versionName = "0.1.0";
export const buildNumber = ${JSON.stringify(build)};
export const commitSha = ${JSON.stringify(sha)};
`;
writeFileSync(resolve(root, "apps/windows/src/build-info.ts"), info);

const confPath = resolve(root, "apps/windows/src-tauri/tauri.conf.json");
const conf = readFileSync(confPath, "utf8").replace(/"version":\s*"[^"]+"/, `"version": "${installer}"`);
writeFileSync(confPath, conf);

const cargoPath = resolve(root, "apps/windows/src-tauri/Cargo.toml");
const cargo = readFileSync(cargoPath, "utf8").replace(/^version = "[^"]+"/m, `version = "${installer}"`);
writeFileSync(cargoPath, cargo);

const lockPath = resolve(root, "apps/windows/src-tauri/Cargo.lock");
const lock = readFileSync(lockPath, "utf8").replace(
  /name = "hermes-bots"\nversion = "[^"]+"/,
  `name = "hermes-bots"\nversion = "${installer}"`,
);
writeFileSync(lockPath, lock);

console.log(`stamped windows ${installer} build ${build} ${sha}`);
